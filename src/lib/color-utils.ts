/** Hex to 0..255 channels; null for anything that is not a 3 or 6 digit hex colour. */
export function hexToRgb(hex: string): [number, number, number] | null {
  const m = /^#?([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(hex.trim());
  if (!m) return null;
  let h = m[1];
  if (h.length === 3) h = h.split("").map((c) => c + c).join("");
  const n = parseInt(h, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

/** WCAG relative luminance, 0 (black) to 1 (white). */
export function relativeLuminance(hex: string): number {
  const rgb = hexToRgb(hex);
  if (!rgb) return 0;
  const [r, g, b] = rgb.map((c) => {
    const s = c / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** Dark ink on light tiles, light ink on dark tiles. 0.179 is the luminance where black and white text reach equal contrast. */
export function labelColorFor(hex: string | null | undefined): string {
  if (!hex) return "var(--label-on-dark)";
  return relativeLuminance(hex) > 0.179 ? "var(--label-on-light)" : "var(--label-on-dark)";
}
